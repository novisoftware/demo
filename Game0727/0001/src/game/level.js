// コース(障害物・的・ゴール)のレイアウト定義。
// y はスタート地点(0)からゴールへ向かうほど負の方向に大きくなる。
// x は左右のブレ幅で、旋回して避ける/狙う操作が必要になるよう散らしてある。

const OBSTACLES = [
  { x: -60, y: -300, r: 30 },
  { x: 90, y: -520, r: 26 },
  { x: -120, y: -720, r: 34 },
  { x: 40, y: -940, r: 28 },
  { x: -20, y: -1180, r: 30 },
  { x: 130, y: -1420, r: 26 },
  { x: -100, y: -1650, r: 32 },
  { x: 60, y: -1900, r: 28 },
  { x: -140, y: -2120, r: 30 },
  { x: 20, y: -2300, r: 26 },
];

const TARGETS = [
  { x: 60, y: -220, r: 16 },
  { x: -90, y: -420, r: 16 },
  { x: 10, y: -620, r: 16 },
  { x: -140, y: -860, r: 16 },
  { x: 120, y: -1060, r: 16 },
  { x: -30, y: -1300, r: 16 },
  { x: 90, y: -1550, r: 16 },
  { x: -110, y: -1780, r: 16 },
  { x: 50, y: -2020, r: 16 },
  { x: -60, y: -2250, r: 16 },
];

const GOAL = { x: 0, y: -2400, r: 34 };

// 呼び出すたびに新しいコピーを返す(リトライ時に的の破壊状態などをリセットするため)。
export function createLevel() {
  return {
    obstacles: OBSTACLES.map((o) => ({ ...o })),
    targets: TARGETS.map((t) => ({ ...t, alive: true })),
    goal: { ...GOAL },
  };
}
